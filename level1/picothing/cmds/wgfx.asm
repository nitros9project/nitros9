********************************************************************
* WGfx - Pico-Thing video graphics showcase (VID-017 acceptance)
*
* A paced, colourful tour of the video pico's graphics command set,
* driven straight through /W0's transparent byte pipe so it exercises
* the firmware, not the driver.  Each scene holds a few seconds:
*
*   1  a sixteen-register palette drawn as filled colour bars
*   2  nested filled ellipses, a white line fan and circle accents
*   3  get/put buffers: a 32x32 gem GPLoaded once, blitted 40 times,
*      then a screen region GetBlk'd and PutBlk'd as a copy
*   4  a get/put buffer set as a FILL PATTERN beside a solid fill
*   5  XOR draw logic: nested boxes, one drawn twice so it erases
*   6  transparent then opaque text laid over a rainbow wash
*   7  reset the logic/pattern, clear, and a closing message
*
* Palette registers are CoCo3 GIME 6-bit RGB (RGBRGB); get/put buffer
* pixels are direct RGB332.  Graphics coordinates are panel pixels
* (1024x480), 16-bit big-endian, X then Y.  The gem and weave images
* and every scene's command stream are generated by scripts/mkvidgfx.py
* into wgfxdat.asm, which this module includes; change the generator,
* not the tables.
*
* Edt/Rev  YYYY/MM/DD  Modified by
* Comment
* ------------------------------------------------------------------
*     1    2026       Created as the VID-017 graphics acceptance demo

                    nam       WGfx
                    ttl       video graphics showcase

                  IFP1
                    use       defsfile
                  ENDC

tylg                set       Prgrm+Objct
atrv                set       ReEnt+rev
rev                 set       $00
edition             set       1

Hold                equ       200       ticks per scene (about 4 seconds)

                    mod       eom,name,tylg,atrv,start,size

                    org       0
path                rmb       1         /W0 path
                    rmb       300       working stack
size                equ       .

name                fcs       /WGfx/
                    fcb       edition

W0Name              fcs       "/W0"

                    use       wgfxdat.asm ; the generated scene streams and images

Msg                 fcc       "wgfx: watch the video screen - 7 colourful scenes"
                    fcb       C$CR
MsgLn               equ       *-Msg

start               leax      Msg,pcr   ; announce on stdout
                    lda       #$01
                    ldy       #MsgLn
                    os9       I$Write

                    leax      W0Name,pcr ; open the video console (transparent pipe)
                    lda       #WRITE.
                    os9       I$Open
                    lbcs      Exit
                    sta       <path

                    leax      Pal,pcr   ; load the sixteen palette registers
                    ldy       #PalLn
                    lbsr      PutV

                    leax      Sc1,pcr   ; scene 1: palette bars
                    ldy       #Sc1Ln
                    lbsr      PutV
                    lbsr      Wait

                    leax      Sc2,pcr   ; scene 2: spirograph
                    ldy       #Sc2Ln
                    lbsr      PutV
                    lbsr      Wait

                    leax      Sc3a,pcr  ; scene 3: define buffer + GPLoad header
                    ldy       #Sc3aLn
                    lbsr      PutV
                    leax      Gem,pcr   ; the gem pixel payload streams right after
                    ldy       #GemLn
                    lbsr      PutV
                    lbsr      Wait
                    leax      Sc3b,pcr  ; blit the gem 40 times, then copy a region
                    ldy       #Sc3bLn
                    lbsr      PutV
                    lbsr      Wait

                    leax      Sc4a,pcr  ; scene 4: define buffer + GPLoad header
                    ldy       #Sc4aLn
                    lbsr      PutV
                    leax      Weave,pcr ; the weave pattern payload streams after
                    ldy       #WeaveLn
                    lbsr      PutV
                    lbsr      Wait
                    leax      Sc4b,pcr  ; patterned fill beside a solid one
                    ldy       #Sc4bLn
                    lbsr      PutV
                    lbsr      Wait

                    leax      Sc5,pcr   ; scene 5: XOR boxes
                    ldy       #Sc5Ln
                    lbsr      PutV
                    lbsr      Wait

                    leax      Sc6,pcr   ; scene 6: text over graphics
                    ldy       #Sc6Ln
                    lbsr      PutV
                    lbsr      Wait

                    leax      Sc7,pcr   ; scene 7: clean up and sign off
                    ldy       #Sc7Ln
                    lbsr      PutV
                    clrb

Close               pshs      b         ; keep exit status across the close
                    lda       <path
                    os9       I$Close
                    puls      b
Exit                os9       F$Exit

* PutV - write Y bytes at X to the video console
PutV                lda       <path
                    os9       I$Write
                    rts

* Wait - hold the current scene so it can be watched
Wait                pshs      x
                    ldx       #Hold
                    os9       F$Sleep
                    puls      x
                    rts

                    emod
eom                 equ       *
                    end
