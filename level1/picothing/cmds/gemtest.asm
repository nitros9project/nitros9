********************************************************************
* GemTest - looping hardware stress for the /V0 get/put buffer hang
*
* wgfx hangs on real hardware at the gem scene but runs to completion
* under usim, and the pico console stays alive during the hang with its
* command fifo fully drained - so the 6809 stops on its own, not blocked
* on the link.  The byte count puts the stop just past the buffer ops, in
* the text that follows; but a progressive fault (a wild fetch corrupting
* the direct page a little each pass, as in VID-020) completes the ops and
* fails later, so a single clean pass proves nothing.
*
* This LOOPS the heavy buffer operations - forty PutBlk of a 32x32 gem, a
* 120x120 GetBlk read-back, two region PutBlk - many times, printing the
* iteration number (hex) to standard output after each pass.  Surviving
* one pass means little; surviving a hundred proves the group clean;
* dying on iteration N proves the damage is cumulative and names the dose.
* Buffers are defined once and reused, so the pool never grows - only the
* per-pixel PSRAM traffic repeats, which is the suspect.
*
* Video bytes go to /V0; markers go to standard output (serial).  The
* command streams and gem image are generated by scripts/mkvidgfx.py into
* gemtestdat.asm, which this module includes.
*
* Edt/Rev  YYYY/MM/DD  Modified by
* Comment
* ------------------------------------------------------------------
*     1    2026       Created to localise the get/put buffer hang

                    nam       GemTest
                    ttl       looping get/put buffer stress

                  IFP1
                    use       defsfile
                  ENDC

tylg                set       Prgrm+Objct
atrv                set       ReEnt+rev
rev                 set       $00
edition             set       1

LoopN               equ       100       heavy-op iterations to run

                    mod       eom,name,tylg,atrv,start,size

                    org       0
path                rmb       1         /V0 path
iter                rmb       1         iteration counter
hexb                rmb       2         two-character hex scratch
                    rmb       300       working stack
size                equ       .

name                fcs       /GemTest/
                    fcb       edition

V0Name              fcs       "/V0"

                    use       gemtestdat.asm ; the generated command streams and gem

M0                  fcc       "gemtest: looping the heavy buffer ops, iter in hex"
                    fcb       C$CR
M0Ln                equ       *-M0
MSet                fcc       "setup ok - starting loop"
                    fcb       C$CR
MSetLn              equ       *-MSet
IterP               fcc       "iter "
IterPLn             equ       *-IterP
MDone               fcc       "ALL DONE - buffer group survived every pass"
                    fcb       C$CR
MDoneLn             equ       *-MDone
NL                  fcb       C$CR

start               leax      M0,pcr    ; banner
                    ldy       #M0Ln
                    lbsr      Say
                    leax      V0Name,pcr ; open the video console
                    lda       #WRITE.
                    os9       I$Open
                    lbcs      Exit
                    sta       <path
* one-time setup: clear, define+load the gem buffer, define the region buffer
                    leax      Clr,pcr
                    ldy       #ClrLn
                    lbsr      PutV
                    leax      D1,pcr
                    ldy       #D1Ln
                    lbsr      PutV
                    leax      G1,pcr
                    ldy       #G1Ln
                    lbsr      PutV
                    leax      Gem,pcr
                    ldy       #GemLn
                    lbsr      PutV
                    leax      D2,pcr
                    ldy       #D2Ln
                    lbsr      PutV
                    leax      MSet,pcr
                    ldy       #MSetLn
                    lbsr      Say
                    clr       <iter
* the heavy loop: 40 blits, a read-back capture, two region stamps, per pass
Loop                leax      P40,pcr
                    ldy       #P40Ln
                    lbsr      PutV
                    leax      GB,pcr
                    ldy       #GBLn
                    lbsr      PutV
                    leax      PR,pcr
                    ldy       #PRLn
                    lbsr      PutV
                    leax      IterP,pcr ; "iter "
                    ldy       #IterPLn
                    lbsr      Say
                    ldb       <iter     ; the pass number in hex
                    lbsr      HexByte
                    leax      NL,pcr
                    ldy       #$0001
                    lbsr      Say
                    inc       <iter
                    lda       <iter
                    cmpa      #LoopN
                    blo       Loop
                    leax      MDone,pcr
                    ldy       #MDoneLn
                    lbsr      Say
                    clrb
Close               pshs      b
                    lda       <path
                    os9       I$Close
                    puls      b
Exit                os9       F$Exit

* Say - write Y bytes at X to standard output
Say                 lda       #$01
                    os9       I$Write
                    rts

* PutV - write Y bytes at X to the video console
PutV                lda       <path
                    os9       I$Write
                    rts

* HexByte - write the value in B as two hex digits to standard output
HexByte             tfr       b,a
                    lsra
                    lsra
                    lsra
                    lsra
                    bsr       Nib
                    sta       <hexb
                    tfr       b,a
                    anda      #$0F
                    bsr       Nib
                    sta       <hexb+$01
                    leax      hexb,u
                    ldy       #$0002
                    lda       #$01
                    os9       I$Write
                    rts
* Nib - low nibble of A to an ASCII hex character in A
Nib                 anda      #$0F
                    cmpa      #$0A
                    blo       Nib0
                    adda      #$07
Nib0                adda      #'0
                    rts

                    emod
eom                 equ       *
                    end
