#!/usr/bin/env python
"""make_piano_keys.py [--preview out.png] - the piano key images in cmds/UmeSymbols16.asm from the four pngs.

2026-09-29 (user: "ditch the piano banner import and cropper, use piano_white.png, piano_white_pressed.png,
piano_black.png, piano_black_pressed.png and layout the 88-key keyboard yourself in block 8, if you need to resize
the images don't do it to the original files"). The pngs one directory up (level2/wildbits/studio9/) are only read:
each is scaled IN MEMORY to the key size UMusE3 lays out (white 12 x 23 dots, black 8 x 15) and every dot becomes the
nearest UmePalette color (cmds/Palette.asm), never nibble 0 (transparent). The pressed black key's colored face
uses palette $9 (Roger 2026-09-30); neutral edges retain their gray/black matching. The white images come in three cut-out
variants - C/F (a black key on the right), D/G/A (both sides), E/B (on the left) - whose top 15 rows leave $00 bytes
(transparent: UMusE3 skips a $00 byte) under the neighboring black keys, so painting a white key never touches them.
The eight images keep the bank layout UMusE3 and Fran expect (from $28C4: CF, DGA, EB in 150-byte slots - 138 bytes of
image + 12 of padding - then Black 60; then the same four pressed), so no offset elsewhere changes. The section between
'* === PIANO KEY SPRITES' and '* === END PIANO KEY SPRITES ===' is rewritten; the rest of the file is left alone.
"""
import os, re, sys
from PIL import Image

PORT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# the images live in the build kit (2026-10-10): S9ART names them, else the kit folder in this tree's own form
PNGDIR = os.environ.get('S9ART') or next((d for d in ('E:/cygwin64/home/taylo/wildbits-buildkit/tools/s9/art',
                                                      '/home/taylo/wildbits-buildkit/tools/s9/art') if os.path.isdir(d)), '')
SYMBOLS = os.path.join(PORT, 'cmds', 'UmeSymbols16.asm')
PALETTE = os.path.join(PORT, 'cmds', 'Palette.asm')
WHITE_W, WHITE_H, BLACK_W, BLACK_H = 12, 23, 8, 15
SLOT = 150                                   # a white image's slot in the bank (25 x 6, the old key size)
BASE = 0x28C4                                # the first key image in UmeSymbols16
BLACK_PRESSED_COLOR = 0x09                   # palette slot requested for the black-key highlight


def palette():
    src = open(PALETTE, encoding='latin-1').read()
    i = src.index('UmePalette          equ       *')
    pal = []
    for m in re.finditer(r'fcb\s+\$([0-9A-Fa-f]{2}),\$([0-9A-Fa-f]{2}),\$([0-9A-Fa-f]{2}),\$[0-9A-Fa-f]{2}', src[i:]):
        b, g, r = (int(x, 16) for x in m.groups())
        pal.append((r, g, b))
        if len(pal) == 16:
            break
    assert len(pal) == 16, 'UmePalette: %d entries' % len(pal)
    return pal


def quantizer(pal):
    # banner16's rule (img2asm.py): nearest by squared RGB; a neutral source dot matches only neutral entries;
    # nibble 0 is transparent and never produced.
    neutral = [k for k, c in enumerate(pal) if k and max(c) - min(c) <= 2]
    cache = {}

    def nib(c):
        n = cache.get(c)
        if n is None:
            cand = neutral if max(c) - min(c) <= 16 and neutral else range(1, 16)
            n = cache[c] = min(cand, key=lambda k: sum((pal[k][i] - c[i]) ** 2 for i in range(3)))
        return n
    return nib


def load(name, w, h, nib):
    im = Image.open(os.path.join(PNGDIR, name)).convert('RGB').resize((w, h), Image.LANCZOS)
    px = im.load()
    return [[nib(px[x, y]) for x in range(w)] for y in range(h)]


def packed(dots, cut_left=False, cut_right=False):
    rows = []
    for y, row in enumerate(dots):
        b = [(row[2 * k] << 4) | row[2 * k + 1] for k in range(len(row) // 2)]
        if y < BLACK_H and len(b) == 6:
            if cut_left:
                b[0] = b[1] = 0
            if cut_right:
                b[4] = b[5] = 0
        rows.append(b)
    return rows


def art(b):
    return ''.join('.' if n == 0 else '%X' % n for x in b for n in (x >> 4, x & 15))


def section(images):
    out = ['* === PIANO KEY SPRITES (generated by tools/gen/make_piano_keys.py - edit the pngs, not these lines) ===',
           '* From ../piano_white.png, piano_white_pressed.png, piano_black.png, piano_black_pressed.png, scaled (copies,',
           '* in memory) to white 12x23 and black 8x15, every dot the nearest UmePalette color (never $0). The white',
           '* pressed black-key face uses $9; neutral border pixels retain their matched gray/black.',
           '* images are cut out ($00 bytes, transparent) under the black keys: CF right, DGA both sides, EB left.',
           '* UMusE3 lays the 88 keys out itself: white i at x = 8 + 12i, a black key 8 dots right of the white on its',
           '* left, rows 205-227 of both bitmaps (block 8). Clean images first, then the same four pressed.']
    off = BASE
    for name, w, h, rows, what in images:
        out.append('')
        out.append('* @sprite %s width=%d height=%d offset=$%04X bytes=%d | %s' % (name, w, h, off, w * h // 2, what))
        out.append('%-28sequ       *' % name)
        for b in rows:
            out.append('                    fcb       %-24s%s' % (','.join('$%02X' % x for x in b), art(b)))
        off += w * h // 2
        if w == WHITE_W:
            pad = SLOT - w * h // 2
            out.append('* @padding %sPad width=12 height=2 offset=$%04X bytes=%d | unused tail of the 150-byte slot' % (name, off, pad))
            out.append('                    fcb       %s' % ','.join(['$00'] * 6))
            out.append('                    fcb       %s' % ','.join(['$00'] * 6))
            off += pad
    assert off == BASE + 3 * SLOT + 30 + 3 * SLOT + 30 + 60 and off == 0x2CC0, 'bank layout moved: $%04X' % off
    out.append('')
    out.append('* === END PIANO KEY SPRITES ===')
    return out


def main():
    pal = palette()
    nib = quantizer(pal)
    wc, wp = load('piano_white.png', WHITE_W, WHITE_H, nib), load('piano_white_pressed.png', WHITE_W, WHITE_H, nib)
    bc = load('piano_black.png', BLACK_W, BLACK_H, nib)
    bp = load('piano_black_pressed.png', BLACK_W, BLACK_H,
              lambda c: BLACK_PRESSED_COLOR if max(c) - min(c) > 16 else nib(c))
    # The white key's one-dot border vanishes at 12 dots wide and neighboring keys would merge into one band: its
    # right column and bottom row take the border color of piano_white.png (right edge, halfway down), up and pressed.
    src = Image.open(os.path.join(PNGDIR, 'piano_white.png')).convert('RGB')
    edge = nib(src.load()[src.size[0] - 1, src.size[1] // 2])
    for dots in (wc, wp):
        for row in dots:
            row[-1] = edge
        dots[-1][:] = [edge] * WHITE_W
    images = []
    for suffix, w, b, how in (('', wc, bc, 'up'), ('Pressed', wp, bp, 'pressed')):
        images += [('PianoWhiteCF' + suffix, WHITE_W, WHITE_H, packed(w, cut_right=True), 'white key %s: C and F (a black key on the right)' % how),
                   ('PianoWhiteDGA' + suffix, WHITE_W, WHITE_H, packed(w, True, True), 'white key %s: D, G and A (black keys both sides)' % how),
                   ('PianoWhiteEB' + suffix, WHITE_W, WHITE_H, packed(w, cut_left=True), 'white key %s: E and B (a black key on the left)' % how),
                   ('PianoBlack' + suffix, BLACK_W, BLACK_H, packed(b), 'black key %s' % how)]
    raw = open(SYMBOLS, 'rb').read().decode('latin-1')
    nl = '\r\n' if '\r\n' in raw[:4000] else '\n'
    lines = raw.split(nl)
    a = next(i for i, l in enumerate(lines) if l.startswith('* === PIANO KEY SPRITES'))
    z = next(i for i, l in enumerate(lines) if l.startswith('* === END PIANO KEY SPRITES'))
    lines[a:z + 1] = section(images)
    open(SYMBOLS, 'wb').write(nl.join(lines).encode('latin-1'))
    print('make_piano_keys: %d images -> %s' % (len(images), os.path.relpath(SYMBOLS, PORT)))
    if len(sys.argv) > 2 and sys.argv[1] == '--preview':
        preview(sys.argv[2], images, pal)


def preview(path, images, pal):
    """The keyboard as UMusE3 lays it out (A0..C8 up, then every key pressed below it), 4x."""
    img = {name: rows for name, w, h, rows, what in images}
    tab = [(0, 0, False), (0, 0, True), (1, 1, False), (1, 1, True), (2, 2, False), (3, 0, False), (3, 0, True),
           (4, 1, False), (4, 1, True), (5, 1, False), (5, 1, True), (6, 2, False)]      # pitch class C..B
    kinds = ['CF', 'DGA', 'EB']
    canvas = Image.new('RGB', (640, 2 * WHITE_H + 4), (233, 234, 231))   # UME's score paper (the VICKY backdrop; 211,212,206 until 2026-10-03)
    px = canvas.load()
    for lit, top in ((False, 0), (True, WHITE_H + 4)):
        for black in (False, True):
            for key in range(88):
                note = key + 21
                white, kind, isblack = tab[note % 12]
                if isblack != black:
                    continue
                i = 7 * (note // 12) + white - 12
                if key == 0:
                    kind = 0                     # A0: nothing on its left
                x = 8 + 12 * i + (8 if black else 0)
                name = ('PianoBlack' if black else 'PianoWhite' + kinds[kind]) + ('Pressed' if lit else '')
                for y, row in enumerate(img[name]):
                    for c, b in enumerate(row):
                        if b:
                            px[x + 2 * c, top + y] = pal[b >> 4]
                            px[x + 2 * c + 1, top + y] = pal[b & 15]
    canvas.resize((640 * 2, (2 * WHITE_H + 4) * 4), Image.NEAREST).save(path)
    print('preview ->', path)


if __name__ == '__main__':
    main()
