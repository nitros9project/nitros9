#!/usr/bin/env python3
"""Generate the data tables for the Pico-Thing video demos wgfx and gemtest.

Both programs drive the video pico through /V0 and carry large tables that
are computed rather than typed: a 32x32 RGB332 gem image, a 16x16 weave
pattern, and (for wgfx) every scene's command stream.  This script is the
source of truth for those tables.  It writes them to

    level1/picothing/cmds/wgfxdat.asm      included by wgfx.asm
    level1/picothing/cmds/gemtestdat.asm   included by gemtest.asm

Both outputs are committed, so the build never needs Python.  After editing
this script, regenerate and commit the outputs with it:

    python3 scripts/mkvidgfx.py            # rewrite the two data files
    python3 scripts/mkvidgfx.py --check    # exit 1 if either is stale

Wire format (docs/copico-video-protocol.md): commands are $1B plus a
sub-code; coordinates are panel pixels (1024x480), 16-bit big-endian, X then
Y; palette registers take CoCo3 GIME 6-bit RGB; get/put buffer pixels are
raw RGB332, row-major.
"""

import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CMDS = os.path.join(ROOT, "level1", "picothing", "cmds")

ESC = 0x1B
W_PANEL, H_PANEL = 1024, 480


# ---- encodings -------------------------------------------------------------

def be(v):
    """16-bit big-endian."""
    return [(v >> 8) & 0xFF, v & 0xFF]


def rgb332(r, g, b):
    """Pack r,g (0..7) and b (0..3) into one RGB332 byte."""
    return ((r & 7) << 5) | ((g & 7) << 2) | (b & 3)


def gime(r, g, b):
    """Pack r,g,b (0..3) as a CoCo3 GIME RGBRGB 6-bit palette value."""
    r1, r0 = (r >> 1) & 1, r & 1
    g1, g0 = (g >> 1) & 1, g & 1
    b1, b0 = (b >> 1) & 1, b & 1
    return (r1 << 5) | (g1 << 4) | (b1 << 3) | (r0 << 2) | (g0 << 1) | b0


# ---- command builders (each returns a byte list) ---------------------------

def Palette(reg, val): return [ESC, 0x31, reg, val]
def FColor(reg):       return [ESC, 0x32, reg]
def SetDPtr(x, y):     return [ESC, 0x40] + be(x) + be(y)
def Line(x, y):        return [ESC, 0x44] + be(x) + be(y)
def Box(x, y):         return [ESC, 0x48] + be(x) + be(y)
def Bar(x, y):         return [ESC, 0x4A] + be(x) + be(y)
def FCircle(r):        return [ESC, 0x53] + be(r)
def FEllipse(a, b):    return [ESC, 0x54] + be(a) + be(b)
def DefGPB(g, b, ln):  return [ESC, 0x29, g, b] + be(ln)
def GetBlk(g, b, x, y, w, h):
    return [ESC, 0x2C, g, b] + be(x) + be(y) + be(w) + be(h)
def PutBlk(g, b, x, y): return [ESC, 0x2D, g, b] + be(x) + be(y)
def PSet(g, b):        return [ESC, 0x2E, g, b]
def LSet(t):           return [ESC, 0x2F, t]
def Bold(on):          return [ESC, 0x3D, on]
def TCharSw(on):       return [ESC, 0x3C, on]
def Cur(col, row):     return [0x02, col + 0x20, row + 0x20]
def txt(s):            return [ord(c) for c in s]
CLR = [0x0C]


def GPLoad(g, b, w, h, nbytes):
    """GPLoad header only (screenType 1 = RGB332); the payload follows it."""
    return [ESC, 0x2B, g, b, 1] + be(w) + be(h) + be(nbytes)


# ---- images ----------------------------------------------------------------

def gem():
    """32x32 radial rainbow gem with a bright core and black corners."""
    img = []
    cx = cy = 15.5
    for y in range(32):
        for x in range(32):
            dx, dy = x - cx, y - cy
            dist = math.sqrt(dx * dx + dy * dy)
            ang = (math.atan2(dy, dx) + math.pi) / (2 * math.pi)
            if dist > 15.5:
                img.append(rgb332(0, 0, 0))
            elif dist < 4:
                img.append(rgb332(7, 7, 3))
            else:
                br = 1.0 - (dist / 16.0)
                r = int((0.5 + 0.5 * math.cos(2 * math.pi * ang)) * 7 * br + 0.5)
                g = int((0.5 + 0.5 * math.cos(2 * math.pi * ang + 2 * math.pi / 3)) * 7 * br + 0.5)
                b = int((0.5 + 0.5 * math.cos(2 * math.pi * ang + 4 * math.pi / 3)) * 3 * br + 0.5)
                img.append(rgb332(r, g, b))
    return img


def weave():
    """16x16 diagonal weave in red, gold, teal and violet threads."""
    threads = [rgb332(7, 0, 0), rgb332(7, 6, 0), rgb332(0, 4, 3), rgb332(2, 0, 3)]
    return [threads[((x + y) % 8) // 2] for y in range(16) for x in range(16)]


# ---- output ----------------------------------------------------------------

class Table:
    """Accumulates labelled fcb blocks in the project's assembly layout."""

    def __init__(self, name, purpose, includer):
        self.lines = [
            "*" * 68,
            f"* {name} - {purpose}",
            "*",
            "* GENERATED by scripts/mkvidgfx.py - do not edit.  Change the",
            "* generator, rerun it and commit both.  Included by "
            f"{includer} with \"use\".",
            "",
        ]

    def block(self, label, data, comment, per_line=16):
        self.lines.append(f"* {comment}")
        self.lines.append(label)
        for i in range(0, len(data), per_line):
            chunk = ",".join(f"${b:02X}" for b in data[i:i + per_line])
            self.lines.append(" " * 20 + f"{'fcb':<10}{chunk}")
        self.lines.append(f"{label + 'Ln':<20}{'equ':<10}*-{label}")
        self.lines.append("")

    def text(self):
        return "\n".join(self.lines).rstrip("\n") + "\n"


def wgfx_tables(gem_img, weave_img):
    t = Table("wgfxdat", "scene streams and images for wgfx", "wgfx.asm")

    # sixteen vivid palette registers
    pal_rgb = [(0, 0, 0), (3, 3, 3), (3, 0, 0), (0, 3, 0),
               (0, 0, 3), (3, 3, 0), (0, 3, 3), (3, 0, 3),
               (3, 1, 0), (2, 0, 3), (0, 2, 2), (3, 2, 2),
               (2, 3, 0), (1, 2, 3), (2, 2, 2), (1, 1, 1)]
    pal = []
    for i, (r, g, b) in enumerate(pal_rgb):
        pal += Palette(i, gime(r, g, b))
    t.block("Pal", pal, "sixteen vivid palette registers (CoCo3 GIME 6-bit RGB)")

    # scene 1: palette bars and a title
    s = CLR[:]
    for i in range(16):
        s += FColor(i) + SetDPtr(i * 64, 40) + Bar((i + 1) * 64 - 1, H_PANEL - 1)
    s += Bold(1) + Cur(42, 0) + txt("VGFX  --  16 COLOUR PALETTE BARS") + Bold(0)
    s += Cur(40, 1) + txt("each bar is one palette register, GIME 6-bit RGB")
    t.block("Sc1", s, "scene 1: sixteen filled palette bars with a title")

    # scene 2: nested filled ellipses, a line fan and circle accents
    s = CLR[:]
    cx, cy = 512, 240
    for a, b, c in [(460, 210, 4), (380, 175, 2), (300, 140, 5), (230, 110, 6),
                    (160, 80, 3), (95, 55, 7), (45, 28, 1)]:
        s += FColor(c) + SetDPtr(cx, cy) + FEllipse(a, b)
    s += FColor(1)
    for k in range(24):
        ang = 2 * math.pi * k / 24
        x = int(cx + 470 * math.cos(ang))
        y = int(cy + 220 * math.sin(ang))
        x = max(0, min(W_PANEL - 1, x))
        y = max(0, min(H_PANEL - 1, y))
        s += SetDPtr(cx, cy) + Line(x, y)
    for k in range(12):
        ang = 2 * math.pi * k / 12
        x = int(cx + 250 * math.cos(ang))
        y = int(cy + 150 * math.sin(ang))
        s += FColor(8 + (k % 8)) + SetDPtr(x, y) + FCircle(18)
    s += Bold(1) + Cur(46, 0) + txt("SPIROGRAPH: fills, a line fan and circles") + Bold(0)
    t.block("Sc2", s, "scene 2: nested ellipses, a line fan and circle accents")

    # scene 3: load the gem, stamp a 10x4 grid, then a labelled region copy
    s = CLR[:] + DefGPB(1, 1, len(gem_img)) + GPLoad(1, 1, 32, 32, len(gem_img))
    t.block("Sc3a", s, "scene 3a: define buffer 1 and start loading the 32x32 gem (payload follows)")
    s = []
    for gy in range(4):
        for gx in range(10):
            s += PutBlk(1, 1, 40 + gx * 96, 60 + gy * 100)
    # capture two whole gems (a 128x32 slab) and stamp the copy in a
    # labelled band below the grid, so it reads as a copy
    s += DefGPB(1, 2, 128 * 32) + GetBlk(1, 2, 40, 60, 128, 32)
    s += Bold(1) + Cur(2, 27) + txt("GetBlk+PutBlk copy ->") + Bold(0)
    s += PutBlk(1, 2, 320, 432) + PutBlk(1, 2, 464, 432)
    s += Bold(1) + Cur(40, 0) + txt("GET/PUT BUFFERS: 40 gem blits, then a labelled copy") + Bold(0)
    t.block("Sc3b", s, "scene 3b: stamp the gem across the panel, then a labelled region copy")

    # scene 4: a pattern-filled bar beside a solid one
    s = CLR[:] + DefGPB(1, 3, len(weave_img)) + GPLoad(1, 3, 16, 16, len(weave_img))
    t.block("Sc4a", s, "scene 4a: define buffer 3 and start loading the 16x16 weave (payload follows)")
    s = PSet(1, 3) + FColor(1) + SetDPtr(40, 60) + Bar(500, 440)
    s += PSet(0, 0) + FColor(12) + SetDPtr(540, 60) + Bar(984, 440)
    s += Bold(1) + Cur(30, 0) + txt("FILL PATTERN (left)  vs  SOLID (right)") + Bold(0)
    t.block("Sc4b", s, "scene 4b: a pattern-filled bar beside a solid one, then pattern off")

    # scene 5: XOR boxes; one drawn twice erases itself
    s = CLR[:] + FColor(5) + SetDPtr(60, 60) + Bar(964, 420)
    s += LSet(3) + FColor(1)
    for k in range(14):
        s += SetDPtr(80 + k * 30, 80 + k * 20) + Box(944 - k * 30, 400 - k * 20)
    s += SetDPtr(400, 180) + Box(624, 300)
    s += SetDPtr(400, 180) + Box(624, 300)
    s += LSet(0)
    s += Bold(1) + Cur(40, 0) + txt("XOR: nested boxes; the centre one drawn twice is erased") + Bold(0)
    t.block("Sc5", s, "scene 5: XOR draw-logic boxes; a doubled box erases itself")

    # scene 6: transparent then opaque text over a rainbow wash
    s = CLR[:]
    for i in range(16):
        s += FColor(i) + SetDPtr(i * 64, 0) + Bar((i + 1) * 64 - 1, H_PANEL - 1)
    s += TCharSw(0) + Bold(1) + Cur(34, 12) + txt("TRANSPARENT BOLD TEXT OVER GRAPHICS") + Bold(0)
    s += Cur(40, 14) + txt("the colour bars show straight through these glyphs")
    s += TCharSw(1) + Cur(44, 17) + txt("...and opaque text lays its own background") + TCharSw(0)
    t.block("Sc6", s, "scene 6: transparent then opaque text laid over a rainbow wash")

    # scene 7: reset logic and pattern, clear, sign off
    s = LSet(0) + PSet(0, 0) + CLR[:]
    s += Bold(1) + Cur(40, 13) + txt("VGFX COMPLETE") + Bold(0)
    s += Cur(34, 15) + txt("palette, fills, curves, buffers, patterns, XOR, text")
    t.block("Sc7", s, "scene 7: reset logic and pattern, clear, closing message")

    t.block("Gem", gem_img, "colourful radial gem sprite (32x32, 1024 bytes RGB332)")
    t.block("Weave", weave_img, "diagonal colour-weave fill pattern (16x16, 256 bytes RGB332)")
    return t.text()


def gemtest_tables(gem_img):
    t = Table("gemtestdat", "buffer command streams and gem for gemtest", "gemtest.asm")
    t.block("Clr", CLR, "setup: clear the panel")
    t.block("D1", DefGPB(1, 1, len(gem_img)), "setup: DefGPB g1/b1 for the gem")
    t.block("G1", GPLoad(1, 1, 32, 32, len(gem_img)), "setup: GPLoad header (gem payload follows)")
    s = []
    for gy in range(4):
        for gx in range(10):
            s += PutBlk(1, 1, 40 + gx * 96, 60 + gy * 100)
    t.block("P40", s, "loop: 40 PutBlk of the gem across a 10x4 grid")
    t.block("D2", DefGPB(1, 2, 120 * 120), "setup: DefGPB g1/b2 for the 120x120 region")
    t.block("GB", GetBlk(1, 2, 40, 60, 120, 120), "loop: GetBlk a 120x120 screen region into b2")
    t.block("PR", PutBlk(1, 2, 760, 300) + PutBlk(1, 2, 880, 300),
            "loop: PutBlk that region back, twice")
    t.block("Gem", gem_img, "the 32x32 RGB332 gem payload")
    return t.text()


def main(argv):
    check = "--check" in argv[1:]
    gem_img, weave_img = gem(), weave()
    outputs = {
        os.path.join(CMDS, "wgfxdat.asm"): wgfx_tables(gem_img, weave_img),
        os.path.join(CMDS, "gemtestdat.asm"): gemtest_tables(gem_img),
    }
    stale = []
    for path, text in outputs.items():
        try:
            with open(path) as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current == text:
            continue
        if check:
            stale.append(path)
        else:
            with open(path, "w") as f:
                f.write(text)
            print(f"wrote {os.path.relpath(path, ROOT)}")
    if stale:
        for path in stale:
            print(f"stale: {os.path.relpath(path, ROOT)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
